const base = "https://paniel-povidomlien-dlia-saitiv.replit.app";
const token = process.env.MOIE_WEBHOOK_TOKEN!;
const { db, ordersTable, orderItemsTable } = await import("@workspace/db");
const { eq } = await import("drizzle-orm");
const { orderMessage } = await import("./src/lib/crm");
const [order] = await db.select().from(ordersTable).limit(1);
const items = await db.select().from(orderItemsTable).where(eq(orderItemsTable.orderId, order!.id));
const body = orderMessage(order!, items);
body.subject = "Перевірка підключення магазину «Пташеня»";
body.message = "Це тестове повідомлення — так виглядатимуть нові замовлення:\n\n" + body.message;
const post = async (p: string, b: unknown) => { const r = await fetch(base + p, { method: "POST", headers: { "Content-Type": "application/json", Authorization: `Bearer ${token}` }, body: JSON.stringify(b) }); return r.status + " " + (await r.text()).slice(0, 300); };
console.log("message:", await post("/api/webhooks/messages", body));
console.log(body.message);
process.exit(0);
